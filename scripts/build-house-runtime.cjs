/* Serialize at build time: Hermes release functions do not retain JavaScript source. */
/* global __dirname */
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')

const root = path.resolve(__dirname, '..')
const engineRoot = path.join(root, 'app/sub-games/house-of-silence/_engine')
function source(file, name) {
  const input = fs.readFileSync(path.join(engineRoot, file), 'utf8')
  const { outputText } = ts.transpileModule(input, {
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
  })
  const context = { exports: {} }
  vm.runInNewContext(outputText, context)
  return context.exports[name].toString()
}

const output = [
  '// Generated by scripts/build-house-runtime.cjs. Edit dungeon.ts/browserRuntime.ts instead.',
  '// Static strings work on Hermes; do not replace with runtime Function.toString().',
  `export const HOUSE_ENGINE_SOURCE =\n  ${JSON.stringify(source('dungeon.ts', 'createDungeon'))}`,
  `export const HOUSE_RUNTIME_SOURCE =\n  ${JSON.stringify(source('browserRuntime.ts', 'bootDungeon'))}`,
  `export const HOUSE_AUDIO_SOURCE =\n  ${JSON.stringify(source('doorAudio.ts', 'createDoorAudio'))}`,
  '',
].join('\n')
const destination = path.join(engineRoot, 'runtimeSource.ts')
const checkRuntime = () =>
  fs.existsSync(destination) && fs.readFileSync(destination, 'utf8') === output
module.exports = { checkRuntime }
if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!checkRuntime()) {
      console.error('House runtime is stale. Run node scripts/build-house-runtime.cjs')
      process.exitCode = 1
    }
  } else {
    fs.writeFileSync(destination, output)
    console.log('Updated House of Silence embedded runtime')
  }
}
